const std = @import("std");
const zinn = @import("zinn");
const ch32 = @import("ch32fun_zig");
pub fn build(b: *std.Build) void {
    const optimize = b.option(std.lang.Optimize, "optimize", "debug, safe, fast, small") orelse .small;
    const ModelChoice = enum { @"mlp32-int8", @"mlp32-int4" };
    const choice = b.option(ModelChoice, "model", "Bundled MLP32 int8 or exported int4") orelse .@"mlp32-int4";
    const Display = enum { ssd1306, ssd1309, ssd1315, sh1106 };
    const display = b.option(Display, "display", "OLED controller") orelse .ssd1306;
    const dep = b.dependency("zinn", .{});
    const hal = b.dependency("ch32fun_zig", .{});
    const fw = ch32.addFirmware(b, hal, .{ .name = "ch32_mnist", .root_source_file = b.path("src/main.zig"), .optimize = optimize, .runtime = .ch32fun_exti });
    const options = b.addOptions();
    options.addOption([]const u8, "display", @tagName(display));
    options.addOption(bool, "trace", b.option(bool, "trace", "Include real hidden activations") orelse false);
    options.addOption(bool, "benchmark", b.option(bool, "benchmark", "Nine inference measurements") orelse false);
    const app = fw.root_module.import_table.get("app").?;
    app.addImport("options", options.createModule());
    var source = dep.path("examples/mnist-desktop/assets/mnist-mlp32-int8.zig");
    if (choice == .@"mlp32-int4") {
        const exporter = b.addExecutable(.{ .name = "export-int4", .root_module = b.createModule(.{ .root_source_file = b.path("tools/export.zig"), .target = b.graph.host, .optimize = .safe }) });
        exporter.root_module.addImport("zinn", dep.module("zinn"));
        const fixture = b.createModule(.{ .root_source_file = source, .target = b.graph.host, .optimize = .safe });
        fixture.addImport("zinn", dep.module("zinn"));
        exporter.root_module.addImport("original", fixture);
        const run = b.addRunArtifact(exporter);
        run.addFileArg(dep.path("examples/mnist-desktop/assets/model.zinn"));
        const generated = run.addOutputFileArg("mnist-int4.zig");
        source = if (b.option(bool,"regenerate-model","Re-export instead of bundled int4") orelse false) generated else b.path("models/mnist-int4.zig");
        const export_step=b.step("export-model", "Export optional int4 through Zinn");
        export_step.dependOn(&b.addInstallFile(generated,"models/regenerated-int4.zig").step);
        const refresh=b.addUpdateSourceFiles();refresh.addCopyFileToSource(generated,"models/mnist-int4.zig");
        b.step("refresh-model","Explicitly replace bundled int4 through Zinn exporter").dependOn(&refresh.step);
        b.getInstallStep().dependOn(&b.addInstallFile(source, "models/mnist-int4.zig").step);
    }
    const core = zinn.addInferenceModule(b, dep, ch32.ch32Target(b), optimize);
    const model = b.createModule(.{ .root_source_file = source, .target = ch32.ch32Target(b), .optimize = optimize });
    model.addImport("zinn", core);
    app.addImport("mnist_model", model);
    app.addImport("zinn_infer", core);
    app.addImport("cycle_benchmark", b.createModule(.{ .root_source_file = dep.path("src/benchmark.zig"), .target = ch32.ch32Target(b), .optimize = optimize }));
    const assembly = fw.getEmittedAsm();
    b.step("assembly","Emit assembly for manual stack/IRQ review").dependOn(&b.addInstallFile(assembly,"reports/firmware.s").step);
    const memory = zinn.addMemoryCheck(b, dep, .{ .name = "ch32_mnist", .elf = fw.getEmittedBin(), .flash_bytes = b.option(u32, "flash-bytes", "Physical Flash") orelse 16384, .ram_bytes = b.option(u32, "ram-bytes", "Physical SRAM") orelse 2048, .stack_bytes = 512, .isr_bytes = 128, .progress = .off });
    b.getInstallStep().dependOn(memory.step);
    b.step("size", "Check final ELF including stack and ISR allowance").dependOn(memory.step);
    b.getInstallStep().dependOn(&b.addInstallFile(fw.getEmittedBin(), "firmware/ch32_mnist.elf").step);
    const bin = fw.addObjCopy(.{ .format = .binary, .basename = "firmware.bin" });
    b.getInstallStep().dependOn(&b.addInstallFile(bin.getOutput(), "firmware/firmware.bin").step);
    const hex = fw.addObjCopy(.{ .format = .hex, .basename = "ch32_mnist.hex" });
    b.getInstallStep().dependOn(&b.addInstallFile(hex.getOutput(), "firmware/ch32_mnist.hex").step);
    const flash = b.addSystemCommand(&.{ "sh", "tools/flash.sh" });
    flash.step.dependOn(b.getInstallStep());
    b.step("flash", "Explicit physical write; disconnect Encoder B from SWIO first").dependOn(&flash.step);
    const host_core = zinn.addInferenceModule(b, dep, b.graph.host, .safe);
    const host_model = b.createModule(.{ .root_source_file = source, .target = b.graph.host, .optimize = .safe });
    host_model.addImport("zinn", host_core);
    const test_options = b.addOptions();
    test_options.addOption(bool, "trace", true);
    test_options.addOption(bool, "benchmark", false);
    test_options.addOption([]const u8, "display", @tagName(display));
    const tests = b.addTest(.{ .root_module = b.createModule(.{ .root_source_file = b.path("src/tests.zig"), .target = b.graph.host, .optimize = b.option(std.lang.Optimize, "test-optimize", "debug or safe") orelse .debug }) });
    tests.root_module.addImport("mnist_model", host_model);
    tests.root_module.addImport("options", test_options.createModule());
    b.step("test", "Hardware independent unit and golden tests").dependOn(&b.addRunArtifact(tests).step);
    const sim = b.addExecutable(.{ .name = "simulate", .root_module = b.createModule(.{ .root_source_file = b.path("src/simulate.zig"), .target = b.graph.host, .optimize = .safe }) });
    sim.root_module.addImport("mnist_model", host_model);
    sim.root_module.addImport("options", test_options.createModule());
    const run_sim = b.addRunArtifact(sim);
    run_sim.addPassthruArgs();
    b.step("simulate", "PBM, golden verification and preprocessing comparison").dependOn(&run_sim.step);
}
